-- =====================================================================
-- TRANSMETRO GUATEMALA - Sistema de control de líneas, estaciones y flota
-- Archivo 01: estructuras (tablas, llaves y restricciones)
-- Motor: PostgreSQL 16 (probado también en PGlite, que es PostgreSQL en WebAssembly)
-- Ejecutar los archivos en orden: 01, 02, 03, 04, 05 (y 06/07 para reportes y pruebas)
-- Las horas se guardan como hora local de Guatemala (UTC-6), sin zona horaria.
-- =====================================================================

DROP SCHEMA IF EXISTS transmetro CASCADE;
CREATE SCHEMA transmetro;
SET search_path TO transmetro, public;

-- ---------------------------------------------------------------------
-- Parámetros configurables (reglas 5, 14 y 15 del enunciado)
-- ---------------------------------------------------------------------
CREATE TABLE parametro_sistema (
    clave        VARCHAR(40)  PRIMARY KEY,
    valor        NUMERIC(10,2) NOT NULL,
    descripcion  VARCHAR(200) NOT NULL
);

-- ---------------------------------------------------------------------
-- Municipalidades (regla 11)
-- ---------------------------------------------------------------------
CREATE TABLE municipalidad (
    id_municipalidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(80)  NOT NULL UNIQUE,
    departamento     VARCHAR(60)  NOT NULL,
    direccion        VARCHAR(150),
    telefono         VARCHAR(20)
);

-- ---------------------------------------------------------------------
-- Líneas y estaciones (reglas 1, 2, 11)
-- ---------------------------------------------------------------------
CREATE TABLE linea (
    id_linea         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(10)  NOT NULL UNIQUE,
    nombre           VARCHAR(100) NOT NULL,
    color_hex        CHAR(7)      NOT NULL DEFAULT '#1F8A4C' CHECK (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    id_municipalidad INT          NOT NULL REFERENCES municipalidad(id_municipalidad),
    estado           VARCHAR(12)  NOT NULL DEFAULT 'PLANIFICADA'
                     CHECK (estado IN ('PLANIFICADA','ACTIVA','SUSPENDIDA')),
    hora_inicio      TIME         NOT NULL DEFAULT '05:00',
    hora_fin         TIME         NOT NULL DEFAULT '21:00'
);

CREATE TABLE estacion (
    id_estacion      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(10)  NOT NULL UNIQUE,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    direccion        VARCHAR(150),
    id_municipalidad INT          NOT NULL REFERENCES municipalidad(id_municipalidad),
    latitud          NUMERIC(9,6) NOT NULL CHECK (latitud BETWEEN 13 AND 18),
    longitud         NUMERIC(9,6) NOT NULL CHECK (longitud BETWEEN -93 AND -88),
    capacidad_anden  INT          NOT NULL CHECK (capacidad_anden > 0),
    es_terminal      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Una estación puede pertenecer a varias líneas; el orden es propio de cada línea
CREATE TABLE linea_estacion (
    id_linea    INT      NOT NULL REFERENCES linea(id_linea) ON DELETE CASCADE,
    id_estacion INT      NOT NULL REFERENCES estacion(id_estacion),
    orden       SMALLINT NOT NULL CHECK (orden > 0),
    PRIMARY KEY (id_linea, id_estacion),
    CONSTRAINT uq_linea_orden UNIQUE (id_linea, orden) DEFERRABLE INITIALLY DEFERRED
);

-- Distancia entre dos estaciones contiguas (regla 12). Se guarda una sola vez por par,
-- con id_estacion_a < id_estacion_b, y sirve para todas las líneas que las unan.
CREATE TABLE tramo (
    id_estacion_a INT          NOT NULL REFERENCES estacion(id_estacion),
    id_estacion_b INT          NOT NULL REFERENCES estacion(id_estacion),
    distancia_km  NUMERIC(6,2) NOT NULL CHECK (distancia_km > 0),
    PRIMARY KEY (id_estacion_a, id_estacion_b),
    CHECK (id_estacion_a < id_estacion_b)
);

-- ---------------------------------------------------------------------
-- Accesos (regla 3) y parqueos (regla 6)
-- ---------------------------------------------------------------------
CREATE TABLE acceso (
    id_acceso   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion INT         NOT NULL REFERENCES estacion(id_estacion) ON DELETE CASCADE,
    numero      SMALLINT    NOT NULL CHECK (numero > 0),
    nombre      VARCHAR(80) NOT NULL,
    tipo        VARCHAR(12) NOT NULL DEFAULT 'PRINCIPAL'
                CHECK (tipo IN ('PRINCIPAL','SECUNDARIO','ACCESIBLE')),
    UNIQUE (id_estacion, numero)
);

CREATE TABLE parqueo (
    id_parqueo      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(10)  NOT NULL UNIQUE,
    nombre          VARCHAR(100) NOT NULL,
    capacidad_buses INT          NOT NULL CHECK (capacidad_buses > 0),
    id_estacion     INT          REFERENCES estacion(id_estacion),  -- solo algunos parqueos están en una estación
    direccion       VARCHAR(150)
);

-- ---------------------------------------------------------------------
-- Buses (reglas 4, 5, 6, 7)
-- ---------------------------------------------------------------------
CREATE TABLE bus (
    id_bus              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_unidad       VARCHAR(10) NOT NULL UNIQUE,
    placa               VARCHAR(10) NOT NULL UNIQUE,
    tipo                VARCHAR(12) NOT NULL DEFAULT 'ARTICULADO'
                        CHECK (tipo IN ('ARTICULADO','CONVENCIONAL')),
    capacidad_pasajeros INT         NOT NULL CHECK (capacidad_pasajeros > 0),
    anio                SMALLINT    NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    estado              VARCHAR(13) NOT NULL DEFAULT 'OPERATIVO'
                        CHECK (estado IN ('OPERATIVO','MANTENIMIENTO')),
    id_linea            INT         REFERENCES linea(id_linea),          -- NULL = sin línea (regla 4)
    id_parqueo          INT         NOT NULL REFERENCES parqueo(id_parqueo) -- nunca sin parqueo (regla 7)
);

CREATE TABLE bus_parqueo_historial (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bus       INT       NOT NULL REFERENCES bus(id_bus) ON DELETE CASCADE,
    id_parqueo   INT       NOT NULL REFERENCES parqueo(id_parqueo),
    desde        TIMESTAMP NOT NULL DEFAULT now(),
    hasta        TIMESTAMP,
    CHECK (hasta IS NULL OR hasta >= desde)
);

-- ---------------------------------------------------------------------
-- Pilotos (regla 9): historial educativo, residencia y comunicación
-- ---------------------------------------------------------------------
CREATE TABLE piloto (
    id_piloto            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpi                  CHAR(13)     NOT NULL UNIQUE CHECK (dpi ~ '^[0-9]{13}$'),
    nombres              VARCHAR(80)  NOT NULL,
    apellidos            VARCHAR(80)  NOT NULL,
    fecha_nacimiento     DATE         NOT NULL CHECK (fecha_nacimiento < DATE '2008-01-01'),
    licencia_numero      VARCHAR(15)  NOT NULL UNIQUE,
    licencia_tipo        CHAR(1)      NOT NULL CHECK (licencia_tipo IN ('A','B','C')),
    fecha_contratacion   DATE         NOT NULL,
    activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    -- residencia
    direccion_residencia VARCHAR(150) NOT NULL,
    zona                 SMALLINT     CHECK (zona BETWEEN 1 AND 25),
    id_municipalidad_residencia INT   NOT NULL REFERENCES municipalidad(id_municipalidad),
    -- comunicación
    telefono_movil       VARCHAR(12)  NOT NULL,
    telefono_residencial VARCHAR(12),
    correo               VARCHAR(100) NOT NULL CHECK (correo LIKE '%_@_%._%'),
    contacto_emergencia_nombre   VARCHAR(100) NOT NULL,
    contacto_emergencia_telefono VARCHAR(12)  NOT NULL
);

CREATE TABLE piloto_estudio (
    id_estudio  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_piloto   INT          NOT NULL REFERENCES piloto(id_piloto) ON DELETE CASCADE,
    nivel       VARCHAR(15)  NOT NULL
                CHECK (nivel IN ('PRIMARIA','BASICO','DIVERSIFICADO','TECNICO','UNIVERSITARIO','POSTGRADO','CAPACITACION')),
    titulo      VARCHAR(120) NOT NULL,
    institucion VARCHAR(120) NOT NULL,
    anio_inicio SMALLINT     NOT NULL CHECK (anio_inicio BETWEEN 1950 AND 2100),
    anio_fin    SMALLINT,
    concluido   BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (anio_fin IS NULL OR anio_fin >= anio_inicio)
);

CREATE TABLE asignacion_piloto_bus (
    id_asignacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bus        INT         NOT NULL REFERENCES bus(id_bus),
    id_piloto     INT         NOT NULL REFERENCES piloto(id_piloto),
    turno         VARCHAR(10) NOT NULL CHECK (turno IN ('MATUTINO','VESPERTINO','NOCTURNO')),
    fecha_inicio  DATE        NOT NULL,
    fecha_fin     DATE,
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
-- un piloto solo tiene una asignación vigente, y un bus un piloto vigente por turno
CREATE UNIQUE INDEX uq_asig_piloto_vigente ON asignacion_piloto_bus (id_piloto) WHERE fecha_fin IS NULL;
CREATE UNIQUE INDEX uq_asig_bus_turno_vigente ON asignacion_piloto_bus (id_bus, turno) WHERE fecha_fin IS NULL;

-- ---------------------------------------------------------------------
-- Guardias de seguridad (regla 10)
-- ---------------------------------------------------------------------
CREATE TABLE guardia (
    id_guardia         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpi                CHAR(13)    NOT NULL UNIQUE CHECK (dpi ~ '^[0-9]{13}$'),
    nombres            VARCHAR(80) NOT NULL,
    apellidos          VARCHAR(80) NOT NULL,
    telefono           VARCHAR(12) NOT NULL,
    fecha_contratacion DATE        NOT NULL,
    activo             BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE asignacion_guardia (
    id_asignacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_guardia    INT         NOT NULL REFERENCES guardia(id_guardia),
    id_acceso     INT         NOT NULL REFERENCES acceso(id_acceso) ON DELETE CASCADE,
    turno         VARCHAR(10) NOT NULL CHECK (turno IN ('MATUTINO','VESPERTINO','NOCTURNO')),
    fecha_inicio  DATE        NOT NULL,
    fecha_fin     DATE,
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX uq_asig_guardia_vigente ON asignacion_guardia (id_guardia) WHERE fecha_fin IS NULL;

-- ---------------------------------------------------------------------
-- PC de trabajo por estación y operador (regla 16) y conectividad (regla 17)
-- ---------------------------------------------------------------------
CREATE TABLE computadora (
    id_computadora INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion    INT         NOT NULL UNIQUE REFERENCES estacion(id_estacion), -- una PC por estación
    hostname       VARCHAR(40) NOT NULL UNIQUE,
    ip_vpn         INET        NOT NULL UNIQUE,
    sistema_operativo VARCHAR(40) NOT NULL DEFAULT 'Windows 11 Pro',
    estado         VARCHAR(12) NOT NULL DEFAULT 'EN_LINEA' CHECK (estado IN ('EN_LINEA','SIN_ENLACE','MANTENIMIENTO'))
);

CREATE TABLE operador (
    id_operador    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpi            CHAR(13)    NOT NULL UNIQUE CHECK (dpi ~ '^[0-9]{13}$'),
    nombres        VARCHAR(80) NOT NULL,
    apellidos      VARCHAR(80) NOT NULL,
    usuario        VARCHAR(30) NOT NULL UNIQUE,
    correo         VARCHAR(100) NOT NULL,
    telefono       VARCHAR(12) NOT NULL,
    turno          VARCHAR(10) NOT NULL CHECK (turno IN ('MATUTINO','VESPERTINO','NOCTURNO')),
    id_computadora INT         NOT NULL REFERENCES computadora(id_computadora),
    activo         BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE enlace_red (
    id_enlace        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion      INT         NOT NULL REFERENCES estacion(id_estacion) ON DELETE CASCADE,
    rol              VARCHAR(9)  NOT NULL CHECK (rol IN ('PRINCIPAL','RESPALDO')),
    medio            VARCHAR(12) NOT NULL CHECK (medio IN ('FIBRA','BANDA_ANCHA','LTE')),
    proveedor        VARCHAR(60) NOT NULL,
    ancho_banda_mbps INT         NOT NULL CHECK (ancho_banda_mbps > 0),
    protocolo_vpn    VARCHAR(12) NOT NULL DEFAULT 'WIREGUARD' CHECK (protocolo_vpn IN ('WIREGUARD','IPSEC')),
    estado           VARCHAR(10) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','CAIDO')),
    UNIQUE (id_estacion, rol)
);

-- ---------------------------------------------------------------------
-- Métodos de pago y tarjeta de acceso (regla 18)
-- ---------------------------------------------------------------------
CREATE TABLE tipo_tarjeta (
    id_tipo_tarjeta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(30)  NOT NULL UNIQUE,
    tarifa          NUMERIC(6,2) NOT NULL CHECK (tarifa >= 0)
);

CREATE TABLE tarjeta_acceso (
    id_tarjeta      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          CHAR(10)     NOT NULL UNIQUE,
    id_tipo_tarjeta INT          NOT NULL REFERENCES tipo_tarjeta(id_tipo_tarjeta),
    saldo           NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (saldo >= 0),
    estado          VARCHAR(10)  NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','BLOQUEADA','VENCIDA')),
    fecha_emision   DATE         NOT NULL DEFAULT current_date
);

CREATE TABLE metodo_pago (
    id_metodo_pago   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(50) NOT NULL UNIQUE,
    usa_saldo_tarjeta BOOLEAN    NOT NULL DEFAULT FALSE,  -- descuenta del saldo de la tarjeta de acceso
    permite_recarga  BOOLEAN     NOT NULL DEFAULT FALSE   -- sirve para recargar una tarjeta
);

CREATE TABLE pago (
    id_pago        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarjeta     INT          REFERENCES tarjeta_acceso(id_tarjeta),
    id_metodo_pago INT          NOT NULL REFERENCES metodo_pago(id_metodo_pago),
    id_estacion    INT          NOT NULL REFERENCES estacion(id_estacion),
    tipo           VARCHAR(13)  NOT NULL CHECK (tipo IN ('RECARGA','COBRO_PASAJE')),
    monto          NUMERIC(8,2) NOT NULL CHECK (monto >= 0),
    fecha          TIMESTAMP    NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Recorridos, visitas a estaciones, lecturas de pasajeros y alertas (reglas 1, 14, 15)
-- ---------------------------------------------------------------------
CREATE TABLE viaje (
    id_viaje           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_linea           INT         NOT NULL REFERENCES linea(id_linea),
    id_bus             INT         NOT NULL REFERENCES bus(id_bus),
    id_piloto          INT         NOT NULL REFERENCES piloto(id_piloto),
    sentido            VARCHAR(6)  NOT NULL CHECK (sentido IN ('IDA','VUELTA')),
    fecha_hora_salida  TIMESTAMP   NOT NULL,
    estado             VARCHAR(10) NOT NULL DEFAULT 'PROGRAMADO' CHECK (estado IN ('PROGRAMADO','EN_CURSO','FINALIZADO'))
);

CREATE TABLE visita (
    id_visita         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viaje          INT          NOT NULL REFERENCES viaje(id_viaje) ON DELETE CASCADE,
    id_estacion       INT          NOT NULL REFERENCES estacion(id_estacion),
    orden             SMALLINT     NOT NULL CHECK (orden > 0),
    hora_programada   TIMESTAMP    NOT NULL,
    hora_llegada_real TIMESTAMP,
    pasajeros_a_bordo INT          CHECK (pasajeros_a_bordo >= 0),
    ocupacion_pct     NUMERIC(5,2),             -- lo calcula el trigger
    espera_extra_min  SMALLINT     NOT NULL DEFAULT 0,  -- regla 15, la calcula el trigger
    UNIQUE (id_viaje, orden)
);

CREATE TABLE lectura_estacion (
    id_lectura         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion        INT       NOT NULL REFERENCES estacion(id_estacion),
    id_linea           INT       NOT NULL REFERENCES linea(id_linea),
    fecha              TIMESTAMP NOT NULL DEFAULT now(),
    pasajeros_esperando INT      NOT NULL CHECK (pasajeros_esperando >= 0)
);

CREATE TABLE alerta (
    id_alerta           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                VARCHAR(20) NOT NULL DEFAULT 'AFORO_ESTACION' CHECK (tipo IN ('AFORO_ESTACION')),
    id_estacion         INT         NOT NULL REFERENCES estacion(id_estacion),
    id_linea            INT         NOT NULL REFERENCES linea(id_linea),
    id_lectura          BIGINT      REFERENCES lectura_estacion(id_lectura),
    fecha               TIMESTAMP   NOT NULL DEFAULT now(),
    pasajeros_esperando INT         NOT NULL,
    umbral              INT         NOT NULL,
    mensaje             VARCHAR(250) NOT NULL,
    atendida            BOOLEAN     NOT NULL DEFAULT FALSE,
    id_bus_refuerzo     INT         REFERENCES bus(id_bus),
    fecha_atencion      TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Bitácora de auditoría (no se puede modificar ni borrar)
-- ---------------------------------------------------------------------
CREATE TABLE bitacora (
    id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       TIMESTAMP   NOT NULL DEFAULT now(),
    usuario_bd  VARCHAR(60) NOT NULL DEFAULT current_user,
    tabla       VARCHAR(40) NOT NULL,
    operacion   VARCHAR(6)  NOT NULL,
    id_registro VARCHAR(40),
    detalle     JSONB
);

-- Índices de apoyo a las consultas de los reportes
CREATE INDEX ix_bus_linea       ON bus (id_linea);
CREATE INDEX ix_bus_parqueo     ON bus (id_parqueo);
CREATE INDEX ix_acceso_estacion ON acceso (id_estacion);
CREATE INDEX ix_le_estacion     ON linea_estacion (id_estacion);
CREATE INDEX ix_visita_estacion ON visita (id_estacion);
CREATE INDEX ix_lectura_est     ON lectura_estacion (id_estacion, fecha);
CREATE INDEX ix_pago_fecha      ON pago (fecha);
